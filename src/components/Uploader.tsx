"use client";

import { useEffect, useRef, useState } from "react";
import { useRouter } from "next/navigation";
import { prepareFile } from "@/lib/compress";
import { store } from "@/lib/client-store";
import { Analysis } from "@/lib/schemas";
import { SAMPLE_TOKEN } from "@/lib/client-store";
import { apiErrorText } from "@/lib/i18n";
import { useMessages } from "@/lib/i18n/client";

const ACCEPT = "application/pdf,image/jpeg,image/png,image/webp";

type DocState = { files: File[]; text: string; mode: "file" | "text" };
const empty = (): DocState => ({ files: [], text: "", mode: "file" });

/** Fictional demo documents in public/samples/ (generated by scripts/make-samples.ts). */
const SAMPLES = {
  er: ["/samples/riverside-bill.pdf", "/samples/summit-eob.pdf"],
  anesthesia: ["/samples/lakeshore-anesthesia-bill.pdf", "/samples/summit-eob-anesthesia.pdf"],
} as const;

export function Uploader() {
  const router = useRouter();
  const m = useMessages();
  const U = m.uploader;
  const STEPS = U.steps;
  const [bill, setBill] = useState<DocState>(empty);
  const [eob, setEob] = useState<DocState>(empty);
  const [showPlan, setShowPlan] = useState(false);
  const [plan, setPlan] = useState({ deductible: "", deductibleMet: "", coinsurancePct: "", inNetwork: "unknown" });
  const [busy, setBusy] = useState(false);
  const [step, setStep] = useState(0);
  const [fast, setFast] = useState(false); // samples load instantly; the steps just play quickly
  const [error, setError] = useState("");
  const startedSample = useRef(false);

  useEffect(() => {
    if (!busy) return;
    const t = setInterval(() => setStep((s) => Math.min(s + 1, STEPS.length - 1)), fast ? 480 : 4500);
    return () => clearInterval(t);
  }, [busy, fast, STEPS.length]);

  async function submit(billFiles: File[], billText: string, eobFiles: File[], eobText: string, sample = false) {
    setError("");
    if (!billFiles.length && !billText.trim()) return setError(U.needBill);
    if (!eobFiles.length && !eobText.trim()) return setError(U.needEob);
    setStep(0);
    setBusy(true);
    try {
      const form = new FormData();
      for (const f of billFiles) form.append("bill", await prepareFile(f));
      for (const f of eobFiles) form.append("eob", await prepareFile(f));
      if (billText.trim()) form.append("billText", billText);
      if (eobText.trim()) form.append("eobText", eobText);
      if (!sample) {
        const ctx: Record<string, unknown> = {};
        if (plan.deductible) ctx.deductible = Number(plan.deductible);
        if (plan.deductibleMet) ctx.deductibleMet = Number(plan.deductibleMet);
        if (plan.coinsurancePct) ctx.coinsurancePct = Number(plan.coinsurancePct);
        if (plan.inNetwork !== "unknown") ctx.inNetwork = plan.inNetwork === "yes";
        form.append("context", JSON.stringify(ctx));
      }
      const res = await fetch("/api/analyze", { method: "POST", body: form });
      const data = await res.json().catch(() => null);
      if (!res.ok || !data) throw new Error(apiErrorText(data, m, m.errors.generic));
      const analysis = data as Analysis;
      store.saveAnalysis(analysis);
      router.push(`/results?id=${analysis.analysisId}`);
    } catch (e) {
      setError((e as Error).message);
      setBusy(false);
    }
  }

  /**
   * Demo path: loads the sample's precomputed result (same rules engine, see src/lib/samples.ts), so the demo
   * works even if the AI service is slow or down. Samples are unlocked for free.
   */
  async function trySample(which: keyof typeof SAMPLES = "er") {
    setError("");
    setStep(0);
    setFast(true);
    setBusy(true);
    try {
      const [data] = await Promise.all([
        fetch(`/samples/${which}.analysis.json`).then((r) => {
          if (!r.ok) throw new Error();
          return r.json();
        }),
        new Promise((r) => setTimeout(r, 2400)),
      ]);
      const analysis = Analysis.parse(data);
      store.saveAnalysis(analysis);
      store.saveUnlock(SAMPLE_TOKEN, analysis.analysisId);
      router.push(`/results?id=${analysis.analysisId}`);
    } catch {
      setError(m.errors.generic);
      setBusy(false);
      setFast(false);
    }
  }

  /** The same sample PDFs sent through the live AI + rules pipeline, for anyone who wants to see it run. */
  async function trySampleLive(which: keyof typeof SAMPLES = "er") {
    setError("");
    setStep(0);
    setFast(false);
    setBusy(true);
    try {
      const [b, e] = await Promise.all(
        SAMPLES[which].map(async (u) => {
          const blob = await fetch(u).then((r) => r.blob());
          return new File([blob], u.split("/").pop()!, { type: "application/pdf" });
        }),
      );
      setBill({ files: [b], text: "", mode: "file" });
      setEob({ files: [e], text: "", mode: "file" });
      await submit([b], "", [e], "", true);
    } catch (e) {
      setError((e as Error).message);
      setBusy(false);
    }
  }

  useEffect(() => {
    const param = new URLSearchParams(window.location.search).get("sample");
    if (param === "1" || param === "2") {
      // Deferred so the sample starts after the first paint (landing page "Try a sample bill" deep link).
      const t = setTimeout(() => {
        if (startedSample.current) return;
        startedSample.current = true;
        trySample(param === "2" ? "anesthesia" : "er");
      }, 0);
      return () => clearTimeout(t);
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  if (busy) {
    return (
      <div className="rounded-2xl border border-stone-200 bg-white p-8 text-center shadow-sm" role="status" aria-live="polite">
        <div className="mx-auto mb-5 h-10 w-10 animate-spin rounded-full border-4 border-teal-700 border-t-transparent" aria-hidden />
        <p className="text-lg font-medium">{STEPS[step]}</p>
        <p className="mt-2 text-sm text-stone-500">{U.wait}</p>
        <ol className="mx-auto mt-6 max-w-xs space-y-1 text-left text-sm">
          {STEPS.map((s, i) => (
            <li key={s} className={i < step ? "text-teal-700" : i === step ? "font-medium" : "text-stone-400"}>
              {i < step ? "✓" : i === step ? "•" : "○"} {s.replace("…", "")}
            </li>
          ))}
        </ol>
      </div>
    );
  }

  return (
    <form
      onSubmit={(e) => {
        e.preventDefault();
        submit(bill.files, bill.mode === "text" ? bill.text : "", eob.files, eob.mode === "text" ? eob.text : "");
      }}
      className="space-y-6"
    >
      <div className="grid gap-4 md:grid-cols-2">
        <DocInput
          title={U.billTitle}
          hint={U.billHint}
          extra={<ItemizedRequest />}
          state={bill}
          onChange={(s) => {
            setBill(s);
            setError("");
          }}
          id="bill"
        />
        <DocInput
          title={U.eobTitle}
          hint={U.eobHint}
          state={eob}
          onChange={(s) => {
            setEob(s);
            setError("");
          }}
          id="eob"
        />
      </div>

      <div className="rounded-2xl border border-stone-200 bg-white p-4">
        <button
          type="button"
          onClick={() => setShowPlan((v) => !v)}
          className="text-sm font-medium text-teal-800 underline-offset-2 hover:underline"
          aria-expanded={showPlan}
        >
          {U.planToggle(showPlan)}
        </button>
        {showPlan && (
          <div className="mt-4 grid gap-3 sm:grid-cols-4">
            <NumField label={U.deductible} value={plan.deductible} onChange={(v) => setPlan({ ...plan, deductible: v })} />
            <NumField label={U.met} value={plan.deductibleMet} onChange={(v) => setPlan({ ...plan, deductibleMet: v })} />
            <NumField label={U.coinsurance} value={plan.coinsurancePct} onChange={(v) => setPlan({ ...plan, coinsurancePct: v })} />
            <label className="text-sm">
              <span className="text-stone-600">{U.inNetwork}</span>
              <select
                className="mt-1 w-full rounded-lg border border-stone-300 bg-white px-3 py-2"
                value={plan.inNetwork}
                onChange={(e) => setPlan({ ...plan, inNetwork: e.target.value })}
              >
                <option value="unknown">{U.notSure}</option>
                <option value="yes">{U.yes}</option>
                <option value="no">{U.no}</option>
              </select>
            </label>
          </div>
        )}
      </div>

      {error && (
        <p role="alert" className="rounded-xl border border-red-200 bg-red-50 p-4 text-red-800">
          {error}
        </p>
      )}

      <div className="flex flex-col gap-3 sm:flex-row sm:items-center">
        <button type="submit" className="rounded-xl bg-teal-700 px-6 py-3 text-base font-semibold text-white shadow-sm hover:bg-teal-800">
          {U.submit}
        </button>
        <button type="button" onClick={() => trySample("er")} className="rounded-xl bg-stone-900 px-6 py-3 text-base font-semibold text-white shadow-sm hover:bg-stone-800">
          {U.sampleEr}
        </button>
        <button type="button" onClick={() => trySample("anesthesia")} className="rounded-xl border border-stone-300 bg-white px-6 py-3 text-base font-medium hover:bg-stone-100">
          {U.sampleAnesthesia}
        </button>
      </div>
      <p className="text-sm text-stone-500">
        {U.samplesPre}
        <a className="underline" href="/samples/riverside-bill.pdf" target="_blank">
          {U.samplesEr}
        </a>
        ,{" "}
        <a className="underline" href="/samples/summit-eob.pdf" target="_blank">
          {U.samplesEob}
        </a>
        ;{" "}
        <a className="underline" href="/samples/lakeshore-anesthesia-bill.pdf" target="_blank">
          {U.samplesAn}
        </a>
        ,{" "}
        <a className="underline" href="/samples/summit-eob-anesthesia.pdf" target="_blank">
          {U.samplesEob}
        </a>
        {U.samplesPost}{" "}
        <button type="button" onClick={() => trySampleLive("er")} className="font-medium text-teal-800 underline underline-offset-2">
          {U.sampleLive}
        </button>
      </p>
      <p className="text-sm text-stone-500">
        {U.privacy}
      </p>
    </form>
  );
}

const ITEMIZED_REQUEST =
  "Hi, I'd like an itemized bill for my visit on [date], including CPT/HCPCS codes, units and charges for each line. " +
  "Please hold the account from collections until I receive it. Thank you.";

/** For people who only have a summary statement: a ready-to-send request for the itemized bill. */
function ItemizedRequest() {
  const U = useMessages().uploader;
  const [copied, setCopied] = useState(false);
  return (
    <details className="mt-2 text-sm">
      <summary className="cursor-pointer font-medium text-teal-800 underline-offset-2 hover:underline">{U.itemizedLink}</summary>
      <div className="mt-2 rounded-xl bg-stone-50 p-3">
        <p className="text-stone-600">{U.itemizedIntro}</p>
        <p lang="en" className="mt-2 rounded-lg border border-stone-200 bg-white p-3 text-stone-800">
          {ITEMIZED_REQUEST}
        </p>
        <button
          type="button"
          onClick={() => {
            navigator.clipboard?.writeText(ITEMIZED_REQUEST);
            setCopied(true);
            setTimeout(() => setCopied(false), 1500);
          }}
          className="mt-2 rounded-lg border border-stone-300 bg-white px-3 py-1.5 hover:bg-stone-100"
        >
          {copied ? U.itemizedCopied : U.itemizedCopy}
        </button>
      </div>
    </details>
  );
}

function DocInput({
  title,
  hint,
  state,
  onChange,
  id,
  extra,
}: {
  title: string;
  hint: string;
  state: DocState;
  onChange: (s: DocState) => void;
  id: string;
  extra?: React.ReactNode;
}) {
  const [drag, setDrag] = useState(false);
  const U = useMessages().uploader;
  const add = (list: FileList | null) => {
    if (!list) return;
    const files = [...state.files, ...Array.from(list)].slice(0, 3);
    onChange({ ...state, files });
  };
  return (
    <div className="rounded-2xl border border-stone-200 bg-white p-5">
      <div className="flex items-start justify-between gap-3">
        <div>
          <h2 className="font-semibold">{title}</h2>
          <p className="mt-1 text-sm text-stone-600">{hint}</p>
          {extra}
        </div>
      </div>
      <div className="mt-3 flex gap-1 rounded-lg bg-stone-100 p-1 text-sm" role="tablist">
        {(["file", "text"] as const).map((m) => (
          <button
            key={m}
            type="button"
            role="tab"
            aria-selected={state.mode === m}
            onClick={() => onChange({ ...state, mode: m })}
            className={`flex-1 rounded-md px-3 py-1.5 ${state.mode === m ? "bg-white font-medium shadow-sm" : "text-stone-600"}`}
          >
            {m === "file" ? U.upload : U.paste}
          </button>
        ))}
      </div>
      {state.mode === "file" ? (
        <>
          <label
            htmlFor={`${id}-files`}
            onDragOver={(e) => {
              e.preventDefault();
              setDrag(true);
            }}
            onDragLeave={() => setDrag(false)}
            onDrop={(e) => {
              e.preventDefault();
              setDrag(false);
              add(e.dataTransfer.files);
            }}
            className={`mt-3 flex cursor-pointer flex-col items-center justify-center rounded-xl border-2 border-dashed px-4 py-8 text-center text-sm transition ${
              drag ? "border-teal-600 bg-teal-50" : "border-stone-300 hover:border-teal-600"
            }`}
          >
            <span className="font-medium text-teal-800">{U.chooseFiles}</span>
            <span className="text-stone-500">{U.dragHint}</span>
          </label>
          <input id={`${id}-files`} type="file" accept={ACCEPT} multiple className="sr-only" onChange={(e) => add(e.target.files)} />
          {state.files.length > 0 && (
            <ul className="mt-3 space-y-1 text-sm">
              {state.files.map((f, i) => (
                <li key={i} className="flex items-center justify-between rounded-lg bg-stone-50 px-3 py-2">
                  <span className="truncate">📄 {f.name}</span>
                  <button
                    type="button"
                    className="ml-2 text-stone-500 hover:text-red-700"
                    aria-label={U.removeFile(f.name)}
                    onClick={() => onChange({ ...state, files: state.files.filter((_, j) => j !== i) })}
                  >
                    ✕
                  </button>
                </li>
              ))}
            </ul>
          )}
        </>
      ) : (
        <label className="mt-3 block text-sm">
          <span className="sr-only">{U.pasteLabel}</span>
          <textarea
            value={state.text}
            onChange={(e) => onChange({ ...state, text: e.target.value })}
            rows={8}
            placeholder={U.pastePlaceholder}
            className="w-full rounded-xl border border-stone-300 p-3"
          />
        </label>
      )}
    </div>
  );
}

function NumField({ label, value, onChange }: { label: string; value: string; onChange: (v: string) => void }) {
  return (
    <label className="text-sm">
      <span className="text-stone-600">{label}</span>
      <input
        type="number"
        inputMode="decimal"
        min={0}
        value={value}
        onChange={(e) => onChange(e.target.value)}
        className="mt-1 w-full rounded-lg border border-stone-300 px-3 py-2"
      />
    </label>
  );
}
